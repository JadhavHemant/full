const generateStockReportHTML = (products = []) => {
  const rows = products.map(p => `
    <tr>
      <td>${p.ProductName || 'N/A'}</td>
      <td>${p.ProductCode || 'N/A'}</td>
      <td>${p.Quantity || 0}</td>
      <td>${p.ReorderLevel || 0}</td>
      <td style="color: ${(p.Quantity || 0) <= (p.ReorderLevel || 0) ? '#ef4444' : '#10b981'}">
        ${(p.Quantity || 0) <= (p.ReorderLevel || 0) ? 'Low' : 'OK'}
      </td>
    </tr>
  `).join('');

  return `
<!DOCTYPE html>
<html>
<head>
  <style>
    body { font-family: Arial, sans-serif; margin: 40px; }
    h1 { color: #4361ee; }
    table { width: 100%; border-collapse: collapse; }
    th { background: #4361ee; color: white; padding: 10px; text-align: left; }
    td { padding: 8px 10px; border-bottom: 1px solid #eee; }
  </style>
</head>
<body>
  <h1>Stock Report</h1>
  <p>Generated: ${new Date().toISOString()}</p>
  <table>
    <thead><tr><th>Product</th><th>Code</th><th>Stock</th><th>Reorder Level</th><th>Status</th></tr></thead>
    <tbody>${rows}</tbody>
  </table>
</body>
</html>`;
};

module.exports = { generateInvoiceHTML, generateSalesOrderHTML, generateStockReportHTML };